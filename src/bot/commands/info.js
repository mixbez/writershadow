export async function infoCommand(ctx) {
  const info = `📖 WriterShadow — помощник для регулярного письма

🚀 НАЧАЛО:
1. /start — первоначальная настройка (выбери канал для публикации)
2. /settings — измени напоминания, AI-провайдера, и другие опции

✍️ НАПИСАНИЕ ЧЕРНОВИКОВ:
• /new <текст> — быстро создать черновик
• /new — без текста — бот попросит написать текст

🔖 ТЕГИ:
• Добавляй теги вручную: ## тема, ## идея
• Если включены AI-теги (/settings) — бот автоматически добавит теги
• /drafts тег — посмотри черновики с конкретным тегом
• Теги удаляются только при публикации в канал

📄 УПРАВЛЕНИЕ ЧЕРНОВИКАМИ:
• /drafts — список всех черновиков (показывает первые 200 символов)
• /drafts [тег] — отфильтровать черновики по тегу
• /drafts_full — полный текст каждого черновика
• /delete — удалить черновики (выбрать по одному)
• /delete all — удалить все черновики сразу
• /combine — объедини несколько черновиков в пост (с AI-мостиками если включено)

📤 ПУБЛИКАЦИЯ:
• /post — опубликовать готовый пост
• Выбери: Опубликовать или Отложить
• После публикации: удалить черновики или сохранить в /drafts

⏰ ЗАПЛАНИРОВАННЫЕ ПОСТЫ:
• Во время публикации выбери "⏰ Отложить"
• Укажи дату (DD.MM.YYYY) и время (HH:MM)
• Бот автоматически опубликует в указанное время (в твоем часовом поясе)

🤖 AI-АССИСТЕНТ:
• /setai — выбери AI-провайдера:
  Groq (бесплатно, быстро)
  Anthropic Claude (свой API ключ)
  WriterShadow Pro (платная подписка)
• /suggest — получи идею для следующего поста на основе последних публикаций

⚙️ НАСТРОЙКИ:
• /settings — измени:
  Время ежедневного напоминания
  Вечерний пинок (если ничего не написал за день)
  Еженедельная сводка (статистика)
  AI-теги (автоматическое добавление тегов)
  Связки между черновиками (AI-переходы при объединении)

📊 СТАТИСТИКА:
• /stats — посмотри сколько символов написал, постов опубликовал

💡 СОВЕТЫ:
• Пиши часто, даже маленькие фрагменты — бот соберёт их в пост
• Используй теги для организации идей
• AI-помощник лучше работает с более длинными текстами
• Расписания работают с твоим часовым поясом (установи в /settings)`;

  await ctx.reply(info);
}
